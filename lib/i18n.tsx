type LanguageContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (text: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('fr');
  const [ready, setReady] = useState(false);

  useEffect(() => {
    const saved = window.localStorage.getItem('sipa-locale') as Locale | null;
    const fromUrl = new URLSearchParams(window.location.search).get('lang') as Locale | null;
    if (fromUrl && ['fr', 'en', 'ar'].includes(fromUrl)) setLocaleState(fromUrl);
    else if (saved && ['fr', 'en', 'ar'].includes(saved)) setLocaleState(saved);
    setReady(true);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
    window.localStorage.setItem('sipa-locale', locale);
  }, [locale]);

  const setLocale = (nextLocale: Locale) => {
    setLocaleState(nextLocale);
    const url = new URL(window.location.href);
    url.searchParams.set('lang', nextLocale);
    window.history.replaceState({}, '', url);
  };

  return (
    <LanguageContext.Provider value={{ locale, setLocale, t: (text) => translations[locale][text] || text }}>
      {ready ? children : null}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}